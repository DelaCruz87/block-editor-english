// ---- Minimal Editor stub: row array + interval replacement, covering a subset of the API used by the plug-in ----
function makeEditor(lines) {
  const doc = { lines: lines.slice() };
  const ed = {
    cm: { state: { doc: {} } }, // Document identity object, used as a cache key for the scan cache
    lineCount() {
      return doc.lines.length;
    },
    getLine(i) {
      return doc.lines[i];
    },
    setLine(i, text) {
      doc.lines[i] = text;
    },
    replaceRange(text, from, to) {
      to = to || from;
      const all = doc.lines;
      let head = '';
      if (from.line > 0) head += all.slice(0, from.line).join('\n') + '\n';
      head += all[from.line].slice(0, from.ch);
      let tail = all[to.line].slice(to.ch);
      if (to.line < all.length - 1) tail += '\n' + all.slice(to.line + 1).join('\n');
      doc.lines = (head + text + tail).split('\n');
    },
    getCursor() {
      return ed._cursor || { line: 0, ch: 0 };
    },
    setCursor(pos) {
      ed._cursor = pos;
    },
    focus() {},
    docLines() {
      return doc.lines;
    },
  };
  return ed;
}

