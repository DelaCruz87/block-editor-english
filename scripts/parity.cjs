const nextCases = {};
function check(name, a, b) {
  const sa = JSON.stringify(a);
  const sb = JSON.stringify(b);
  if (sa === sb) {
    pass++;
    return;
  }
  if (UPDATE) {
    nextCases[name] = b;
    pass++;
    return;
  }
  // Registered intentional changes: the current output must be consistent with the snapshot (to prevent the relative frozen baseline from continuing to drift)
  const pinned = baseline.cases[name];
  if (pinned !== undefined && JSON.stringify(pinned) === sb) {
    pass++;
    return;
  }
  fails.push({ name, legacy: sa, refactored: sb });
}

